/**
 * Random, never the one already on screen: a phrase that changes to itself
 * looks like the app has frozen.
 */
export function nextPhrase(
  phrases: readonly string[],
  previous?: string,
): string {
  const index = Math.floor(Math.random() * phrases.length);
  const phrase = phrases[index];
  return phrase === previous ? phrases[(index + 1) % phrases.length] : phrase;
}

/** Rotates a phrase every few seconds. Mount it only while work runs. */
export function useRotatingPhrase(
  phrases: readonly string[],
  intervalMs = 2600,
): string {
  const [phrase, setPhrase] = useState(() => nextPhrase(phrases));
  useEffect(() => {
    const timer = setInterval(
      () => setPhrase((current) => nextPhrase(phrases, current)),
      intervalMs,
    );
    return () => clearInterval(timer);
  }, [phrases, intervalMs]);
  return phrase;
}
