/** Editable SVG sources remain in docs/design/assets; only portable PNGs reach Metro. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { initWasm, Resvg } from "@resvg/resvg-wasm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const design = join(root, "../docs/design");
const catalog = JSON.parse(
  readFileSync(join(design, "character-options.json"), "utf8"),
);
await initWasm(
  readFileSync(join(root, "node_modules/@resvg/resvg-wasm/index_bg.wasm")),
);
const artDir = join(root, "assets/workshop");
mkdirSync(artDir, { recursive: true });
const font = readFileSync(join(root, "assets/fonts/Poppins-Regular.ttf"));
const render = (svg, width) => {
  const image = new Resvg(svg, {
    fitTo: { mode: "width", value: width },
    font: { fontBuffers: [font], loadSystemFonts: false },
  });
  const result = image.render();
  const png = result.asPng();
  result.free();
  image.free();
  return png;
};
const strip = (svg) =>
  svg.replace(/<\/?svg\b[^>]*>/g, "").replace(/<title>.*?<\/title>/g, "");
const groups = [catalog.characters, catalog.outfits, catalog.quirks];
const extra = [
  "set_bakery",
  "set_treehouse",
  "set_museum",
  "set_moon",
  "prob_cake",
  "prob_gravity",
  "prob_map",
  "prob_monster",
  "item_whisk",
  "item_jam",
  "item_kazoo",
  "item_boot",
  "item_umbrella",
  "item_tape",
];
const options = [
  ...groups.flat(),
  ...extra.map((id) => ({ id, asset: `assets/world-items/${id}.svg` })),
];
const svgByKey = new Map();
for (const option of options) {
  if (!/^[a-z][a-z0-9_]*$/.test(option.id))
    throw new Error(`Invalid asset key: ${option.id}`);
  const svg = readFileSync(join(design, option.asset), "utf8");
  if (!svg.includes('viewBox="0 0 300 300"'))
    throw new Error(`Unexpected canvas: ${option.id}`);
  svgByKey.set(option.id, strip(svg));
  writeFileSync(join(artDir, `${option.id}.png`), render(svg, 600));
}
writeFileSync(
  join(root, "src/lib/workshopAssets.ts"),
  `// Generated by scripts/build-workshop-assets.mjs. Do not edit.\nimport type { ImageSourcePropType } from "react-native";\nexport const workshopAssets: Record<string, ImageSourcePropType> = {\n${options.map((o) => `  ${o.id}: require("../../assets/workshop/${o.id}.png"),`).join("\n")}\n};\n`,
);
// Copy the seed fixture through the same repeatable import path.
writeFileSync(
  join(root, "convex/fixtures/hero-options.json"),
  `${JSON.stringify(catalog, null, 2)}\n`,
);
const exports = join(design, "exports");
const escapeXml = (s) => s.replaceAll("&", "&amp;").replaceAll("<", "&lt;");
for (let group = 0; group < 4; group++) {
  let content = "";
  for (const [row, character] of catalog.characters
    .slice(group * 4, group * 4 + 4)
    .entries()) {
    for (const [col, outfit] of catalog.outfits.entries()) {
      content += `<g transform="translate(${col * 150} ${row * 175})"><svg width="150" height="150" viewBox="0 0 300 300">${svgByKey.get(character.id)}${svgByKey.get(outfit.id)}</svg><text x="75" y="160" text-anchor="middle" font-family="Poppins" font-size="9">${escapeXml(character.displayLabel)}</text><text x="75" y="171" text-anchor="middle" font-family="Poppins" font-size="9">${escapeXml(outfit.displayLabel)}</text></g>`;
    }
  }
  const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="2400" height="700" viewBox="0 0 2400 700"><rect width="2400" height="700" fill="#F5F3EB"/>${content}</svg>`;
  writeFileSync(
    join(exports, `workshop-pairings-${group + 1}.png`),
    render(sheet, 2400),
  );
}
let quirks = "";
for (const [i, quirk] of catalog.quirks.entries()) {
  quirks += `<g transform="translate(${(i % 8) * 180} ${Math.floor(i / 8) * 200})"><svg width="180" height="180" viewBox="0 0 300 300">${svgByKey.get(quirk.id)}</svg><text x="90" y="194" text-anchor="middle" font-family="Poppins" font-size="11">${escapeXml(quirk.displayLabel)}</text></g>`;
}
writeFileSync(
  join(exports, "workshop-quirks.png"),
  render(
    `<svg xmlns="http://www.w3.org/2000/svg" width="1440" height="400" viewBox="0 0 1440 400"><rect width="1440" height="400" fill="#F5F3EB"/>${quirks}</svg>`,
    1440,
  ),
);

let worldItems = "";
for (const [i, key] of extra.entries()) {
  worldItems += `<g transform="translate(${(i % 7) * 180} ${Math.floor(i / 7) * 200})"><svg width="180" height="180" viewBox="0 0 300 300">${svgByKey.get(key)}</svg><text x="90" y="194" text-anchor="middle" font-family="Poppins" font-size="11">${key}</text></g>`;
}
writeFileSync(
  join(exports, "workshop-world-items.png"),
  render(
    `<svg xmlns="http://www.w3.org/2000/svg" width="1260" height="400" viewBox="0 0 1260 400"><rect width="1260" height="400" fill="#F5F3EB"/>${worldItems}</svg>`,
    1260,
  ),
);

console.log(
  `Built ${options.length} PNGs and six artwork review sheets from SVG sources.`,
);
