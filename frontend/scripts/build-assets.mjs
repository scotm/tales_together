/**
 * Inlines the EPUB and cover fonts (plus the resvg wasm) as base64 so Convex
 * actions can ship them inside the bundle. Convex cannot read the filesystem.
 *
 * Run after replacing anything in assets/fonts/: `npm run epub:assets`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontDir = join(root, "assets/fonts");
const chunk = (value, size = 96) =>
  value
    .match(new RegExp(`.{1,${size}}`, "g"))
    .map((part) => JSON.stringify(part))
    .join(" +\n    ");

const base64 = (name) => readFileSync(join(fontDir, name)).toString("base64");

writeFileSync(
  join(root, "convex/epub/assets.ts"),
  `// Generated by scripts/build-assets.mjs. Do not edit.
export const FONT_FILES = [
  {
    id: "font-body",
    filename: "Lexend-Regular.woff2",
    base64:
    ${chunk(base64("Lexend-Regular.woff2"))},
  },
  {
    id: "font-display",
    filename: "Fraunces-Bold.woff2",
    base64:
    ${chunk(base64("Fraunces-Bold.woff2"))},
  },
] as const;
`,
);

const wasm = gzipSync(
  readFileSync(join(root, "node_modules/@resvg/resvg-wasm/index_bg.wasm")),
  { level: 9 },
).toString("base64");

writeFileSync(
  join(root, "convex/cover/assets.ts"),
  `// Generated by scripts/build-assets.mjs. Do not edit.
export const RESVG_WASM_GZIP_BASE64 =
  ${chunk(wasm)};

export const COVER_FONT_FILES = [
  {
    filename: "Fraunces-Bold.ttf",
    base64:
    ${chunk(base64("Fraunces-Bold.ttf"))},
  },
  {
    filename: "Lexend-Regular.ttf",
    base64:
    ${chunk(base64("Lexend-Regular.ttf"))},
  },
] as const;
`,
);
